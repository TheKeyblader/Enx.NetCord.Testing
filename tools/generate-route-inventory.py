#!/usr/bin/env python3
"""Derives the REST route inventory embedded in the fake from the pinned Discord OpenAPI spec.

Usage:
    python3 tools/generate-route-inventory.py <path/to/openapi.json> <spec-commit-sha> \
        [src/Enx.NetCord.Testing/Rest/RouteInventory.g.cs]

The tool runs offline, outside the build, and its output is checked in. Only
(method, template, operationId, security alternatives) are kept: the fake never reads the
spec at runtime (ADR 0005). OAuth2 scopes are deliberately dropped because the fake does not
model Bearer identities yet. Re-run it during /parity/sync and diff the result.
"""

import json
import sys

METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")


def security_flags(operation, key):
    alternatives = operation.get("security")
    if alternatives is None:
        raise SystemExit(f"{key}: operation has no security alternatives")
    flags = []
    for alternative in alternatives:
        if not alternative:
            flags.append("Anonymous")
            continue
        for scheme in alternative:
            if scheme == "BotToken":
                flags.append("Bot")
            elif scheme == "OAuth2":
                flags.append("OAuth2")
            else:
                raise SystemExit(f"{key}: unknown security scheme {scheme}")
    ordered = [name for name in ("Bot", "OAuth2", "Anonymous") if name in flags]
    return " | ".join(f"RouteSecurity.{name}" for name in ordered)


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    spec_path, commit = sys.argv[1], sys.argv[2]
    output = (
        sys.argv[3]
        if len(sys.argv) > 3
        else "src/Enx.NetCord.Testing/Rest/RouteInventory.g.cs"
    )

    with open(spec_path, encoding="utf-8") as handle:
        spec = json.load(handle)

    rows = []
    for template, item in spec["paths"].items():
        for method in METHODS:
            operation = item.get(method)
            if operation is None:
                continue
            key = f"{method.upper()} {template}"
            rows.append(
                (
                    template,
                    method.upper(),
                    operation["operationId"],
                    security_flags(operation, key),
                )
            )
    rows.sort(key=lambda row: (row[0], row[1]))

    lines = [
        "// <auto-generated>",
        "// Generated by tools/generate-route-inventory.py from discord-api-spec specs/openapi.json.",
        "// Do not edit by hand: re-run the tool during /parity/sync.",
        "// </auto-generated>",
        "",
        "namespace Enx.NetCord.Testing.Rest;",
        "",
        "internal static partial class RouteInventory",
        "{",
        "    /// <summary>The discord-api-spec commit the inventory was derived from.</summary>",
        f'    internal const string SpecificationCommit = "{commit}";',
        "",
        "    /// <summary>Operations documented by the pinned Discord OpenAPI specification.</summary>",
        "    internal static readonly RouteOperation[] Specification =",
        "    [",
    ]
    for template, method, operation_id, security in rows:
        lines.append(
            f'        new("{method}", "{template}", "{operation_id}", {security}),'
        )
    lines += ["    ];", "}", ""]

    with open(output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {len(rows)} operations to {output}")


if __name__ == "__main__":
    main()
